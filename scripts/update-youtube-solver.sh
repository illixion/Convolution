#!/usr/bin/env bash
# Embeds yt-dlp's EJS challenge solver (https://github.com/yt-dlp/ejs) in the
# app as Hypnos/Hypnos/Services/YouTube/YouTubeSolverScript.swift.
#
# YouTubePlayerScript runs it in JavaScriptCore to solve the `n` (and
# signature) challenges of YouTube's player JS, which the TV client's stream
# URLs need. It is a Swift string inside `#if HYPNOS_YOUTUBE` rather than a
# bundle resource, so a submission build carries none of it.
#
# Run it when YouTube changes its player JS and an updated solver is out:
#
#   scripts/update-youtube-solver.sh <dir holding lib.min.js and core.min.js> <version>
#
# The files are in the `yt-dlp-ejs` Python package (yt_dlp_ejs/yt/solver/,
# e.g. inside Homebrew's yt-dlp: $(brew --prefix yt-dlp)/libexec/lib/python3.*/site-packages)
# or a release of github.com/yt-dlp/ejs (yt.solver.lib.min.js, yt.solver.core.min.js).
set -euo pipefail

if [ $# -ne 2 ]; then
    echo "usage: $0 <solver dir> <version>" >&2
    exit 64
fi
dir=$1
version=$2
lib=$dir/lib.min.js
core=$dir/core.min.js
[ -f "$lib" ] || lib=$dir/yt.solver.lib.min.js
[ -f "$core" ] || core=$dir/yt.solver.core.min.js
for file in "$lib" "$core"; do
    [ -f "$file" ] || { echo "missing $file" >&2; exit 66; }
    # The Swift raw string below is delimited by ##"""; neither may appear.
    if /usr/bin/grep -q -e '"""##' -e '\\##' "$file"; then
        echo "$file contains the raw-string delimiter; widen it in this script" >&2
        exit 65
    fi
done

out=$(cd "$(dirname "$0")/.." && pwd)/Hypnos/Hypnos/Services/YouTube/YouTubeSolverScript.swift
{
    echo '/*'
    echo ' Hypnos - yt-dlp'"'"'s EJS challenge solver, generated by'
    echo ' scripts/update-youtube-solver.sh; do not edit by hand.'
    echo ''
    echo " yt-dlp-ejs $version: the solver is Unlicense; it bundles meriyah (ISC) and"
    echo ' astring (MIT), whose notices are kept in the script text below and in'
    echo ' THIRD_PARTY_NOTICES.md. See YouTubePlayerScript for how it is run.'
    echo ' */'
    echo ''
    echo '#if HYPNOS_YOUTUBE'
    echo ''
    echo 'enum YouTubeSolverScript {'
    echo "    static let version = \"$version\""
    echo ''
    echo '    /// Defines `lib` (meriyah and astring).'
    echo '    static let lib = ##"""'
    cat "$lib"
    echo ''
    echo '"""##'
    echo ''
    echo '    /// Defines `jsc(input)`, which needs `lib`'"'"'s members as globals.'
    echo '    static let core = ##"""'
    cat "$core"
    echo ''
    echo '"""##'
    echo '}'
    echo ''
    echo '#endif'
} > "$out"
echo "wrote $out ($(wc -c < "$out" | tr -d ' ') bytes, yt-dlp-ejs $version)"
