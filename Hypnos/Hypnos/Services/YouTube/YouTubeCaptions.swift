/*
 Hypnos - a YouTube video's own subtitles (sideload builds only: `HYPNOS_YOUTUBE`)

 The visionOS client's player answer lists the video's caption tracks as
 signed `timedtext` URLs. They need no PO token and no cookies (checked
 2026-10-27), and `fmt=json3` gives cues with times. Offered:
 - every track a person made (uploaded subtitles),
 - the automatic track, which YouTube makes in the video's spoken language.
 - YouTube's own machine translation of a track (`tlang`), on request: a
   "Translate to…" list in the subtitle menu offers every language it
   lists, and when the automatic track isn't in the viewer's language (the
   one in Settings → AI Features → AI Captions → Translate To, else the system's) a
   translation into it is listed beside it. Only a picked language is
   requested, as YouTube answers 429 to a run of them.

 The automatic and translated tracks are flagged (`isAutoGenerated`,
 `isTranslated`), so they are listed but never picked on their own
 (`SubtitlePreference.initialTrack`).

 A video with several audio languages (YouTube's dubs) lists its captions
 once for all of them. The automatic track may then be in a language other
 than the one the picture is playing in, so the one offered is the one in the
 viewer's language when there is one, else the one the default audio goes
 with, never merely the first listed.
 */

#if HYPNOS_YOUTUBE

import DebugTrace
import Foundation

struct YouTubeCaptionTrack: Sendable {
    var languageCode: String
    var name: String?
    var isAutoGenerated: Bool
    var baseURL: URL

    init?(_ json: [String: Any]) {
        guard let language = json["languageCode"] as? String,
              let base = (json["baseUrl"] as? String).flatMap(URL.init(string:)) else { return nil }
        languageCode = language
        isAutoGenerated = json["kind"] as? String == "asr"
        baseURL = base
        let names = json["name"] as? [String: Any]
        name = (names?["simpleText"] as? String) ?? ((names?["runs"] as? [[String: Any]])?.first?["text"] as? String)
    }
}

/// What the player answer says about a video's captions.
struct YouTubeCaptionList: Sendable {
    var tracks: [YouTubeCaptionTrack]
    var translations: [SubtitleTranslationLanguage]
    /// Index into `tracks` of the track the default audio goes with.
    var defaultTrackIndex: Int?
}

/// The language the viewer wants to read in.
enum YouTubeCaptionLanguage {
    /// `SubtitleTranslationSupport.targetKey`, which only iOS and macOS compile.
    private static let targetKey = "translation.target"

    static var preferred: Locale.Language {
        let saved = UserDefaults.standard.string(forKey: targetKey) ?? ""
        return Locale.Language(identifier: saved.isEmpty ? (Locale.preferredLanguages.first ?? "en") : saved)
    }

    /// The language `code` ("en", "pt-BR", "zh-Hans") is, ignoring region.
    static func base(_ code: String) -> String? {
        Locale.Language(identifier: code).languageCode?.identifier
    }

    /// Which of YouTube's translation codes is `wanted`: the same code and
    /// script or region if it has one, else the first with the same language.
    static func code(for wanted: Locale.Language, in languages: [SubtitleTranslationLanguage]) -> String? {
        guard let language = wanted.languageCode?.identifier else { return nil }
        let same = languages.filter { base($0.code) == language }
        return same.first { Locale.Language(identifier: $0.code) == wanted }?.code
            ?? same.first { $0.code.caseInsensitiveCompare(wanted.minimalIdentifier) == .orderedSame }?.code
            ?? same.first { $0.code == language }?.code
            ?? same.first?.code
    }
}

extension SubtitleSource {
    /// The video's own subtitles and its automatic captions, with YouTube's
    /// translations of them. Nothing is requested before the YouTube
    /// approval (`YouTubeInnertube` checks it).
    static func youTube(_ id: YouTubeVideoID) -> SubtitleSource {
        let listing = YouTubeCaptionListing(id: id)
        return SubtitleSource(
            id: "youtube:\(id.rawValue)",
            tracks: { try await listing.tracks() },
            data: { track in try await listing.srt(for: track) },
            translationLanguages: { try await listing.translations() }
        )
    }
}

/// One video's caption tracks, listed once so a pick fetches the URL the
/// list came with.
private actor YouTubeCaptionListing {
    private struct Listed {
        var tracks: [LibrarySubtitleTrack]
        var urls: [Int: URL]
        /// The track a translation is made from: the automatic one offered.
        var translationBase: URL?
        var translations: [SubtitleTranslationLanguage]
    }

    let id: YouTubeVideoID
    private var listed: Listed?

    init(id: YouTubeVideoID) { self.id = id }

    func tracks() async throws -> [LibrarySubtitleTrack] { try await list().tracks }
    func translations() async throws -> [SubtitleTranslationLanguage] { try await list().translations }

    private func list() async throws -> Listed {
        if let listed { return listed }
        let all = try await YouTubeInnertube.shared.captionList(id)
        let preferred = YouTubeCaptionLanguage.preferred
        let wanted = preferred.languageCode?.identifier

        // People's tracks first, then one automatic track: the one in the
        // viewer's language, else the one the default audio goes with, else
        // the first.
        let manual = all.tracks.filter { !$0.isAutoGenerated }
        let autos = all.tracks.filter(\.isAutoGenerated)
        let defaultTrack = all.defaultTrackIndex.flatMap { all.tracks.indices.contains($0) ? all.tracks[$0] : nil }
        let auto = autos.first { YouTubeCaptionLanguage.base($0.languageCode) == wanted }
            ?? defaultTrack.flatMap { $0.isAutoGenerated ? $0 : nil }
            ?? autos.first
        let offered = manual + (auto.map { [$0] } ?? [])

        var urls: [Int: URL] = [:]
        var tracks = offered.enumerated().map { index, caption in
            urls[index] = caption.baseURL
            return LibrarySubtitleTrack(id: index, sourceId: "youtube", language: caption.languageCode,
                                        name: caption.isAutoGenerated ? nil : caption.name,
                                        isAutoGenerated: caption.isAutoGenerated)
        }
        // Spoken in another language than the viewer reads: a translation
        // into theirs goes before it, which is what they'll want.
        if let auto, YouTubeCaptionLanguage.base(auto.languageCode) != wanted,
           let code = YouTubeCaptionLanguage.code(for: preferred, in: all.translations) {
            tracks.insert(.translated(to: code), at: manual.count)
        }
        AppLogger.subtitles.info("YouTube captions: \(all.tracks.count, privacy: .public) listed (\(autos.count, privacy: .public) automatic), \(tracks.count, privacy: .public) offered, \(all.translations.count, privacy: .public) translation languages")
        let result = Listed(tracks: tracks, urls: urls, translationBase: auto?.baseURL ?? manual.first?.baseURL,
                            translations: all.translations)
        listed = result
        return result
    }

    func srt(for track: LibrarySubtitleTrack) async throws -> Data {
        let listing = try await list()
        let url: URL
        var translateTo: String?
        if track.isTranslated {
            guard let base = listing.translationBase, let code = track.language else { throw URLError(.resourceUnavailable) }
            url = base
            translateTo = code
        } else {
            guard let own = listing.urls[track.id] else { throw URLError(.resourceUnavailable) }
            url = own
        }
        var components = URLComponents(url: url, resolvingAgainstBaseURL: false)!
        components.queryItems = (components.queryItems ?? []).filter { $0.name != "fmt" && $0.name != "tlang" }
            + [URLQueryItem(name: "fmt", value: "json3")]
            + (translateTo.map { [URLQueryItem(name: "tlang", value: $0)] } ?? [])
        let (data, response) = try await URLSession.shared.data(from: components.url!)
        let status = (response as? HTTPURLResponse)?.statusCode ?? -1
        guard status == 200 else {
            throw URLError(.badServerResponse, userInfo: [NSLocalizedDescriptionKey: "Captions: HTTP \(status)"])
        }
        return Data(YouTubeCaptionConverter.subRip(fromJSON3: data).utf8)
    }
}

enum YouTubeCaptionConverter {
    /// `json3` events as SubRip. Automatic captions are a two-line roll-up:
    /// each event is one new line, newline-only "append" events scroll the
    /// window, and the line before stays on screen under the new one, so
    /// events overlap. Showing only the new line made the box change height
    /// on every cue (a long line wraps to two rows, the next short one is
    /// one), so a roll-up track is rebuilt the way YouTube draws it: each
    /// cue is the previous line over the current one, while the previous
    /// line was still up when this one began. Cues end where the next begins.
    /// Tracks without append events (made by a person) are left as they are.
    static func subRip(fromJSON3 data: Data) -> String {
        guard let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let events = json["events"] as? [[String: Any]] else { return "" }
        let isRollUp = events.contains { ($0["aAppend"] as? NSNumber)?.intValue == 1 }
        var cues: [(start: Int, end: Int, text: String)] = []
        var previous: (end: Int, line: String)?
        for event in events {
            guard let start = (event["tStartMs"] as? NSNumber)?.intValue,
                  let segs = event["segs"] as? [[String: Any]] else { continue }
            let lines = segs.compactMap { $0["utf8"] as? String }.joined()
                .split(separator: "\n", omittingEmptySubsequences: true)
                .map { $0.trimmingCharacters(in: .whitespaces) }
                .filter { !$0.isEmpty }
            guard !lines.isEmpty else { continue }
            let duration = (event["dDurationMs"] as? NSNumber)?.intValue ?? 2000
            let end = start + max(duration, 1)
            var text = lines.joined(separator: "\n")
            if isRollUp {
                if let previous, previous.end > start { text = previous.line + "\n" + text }
                previous = (end, lines.last!)
            }
            cues.append((start, end, text))
        }
        for index in cues.indices.dropLast() {
            cues[index].end = min(cues[index].end, max(cues[index + 1].start, cues[index].start + 1))
        }
        return cues.enumerated().map { index, cue in
            "\(index + 1)\n\(timestamp(cue.start)) --> \(timestamp(cue.end))\n\(cue.text)\n"
        }.joined(separator: "\n")
    }

    private static func timestamp(_ ms: Int) -> String {
        String(format: "%02d:%02d:%02d,%03d", ms / 3_600_000, ms / 60_000 % 60, ms / 1000 % 60, ms % 1000)
    }
}

