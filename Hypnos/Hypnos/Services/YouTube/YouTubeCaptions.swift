/*
 Hypnos - a YouTube video's own subtitles (sideload builds only: `HYPNOS_YOUTUBE`)

 The visionOS client's player answer lists the video's caption tracks as
 signed `timedtext` URLs. They need no PO token and no cookies (checked
 2026-10-27), and `fmt=json3` gives cues with times. Offered:
 - every track a person made (uploaded subtitles), and
 - the automatic track, which YouTube makes in the video's spoken language.
 Translations (`tlang`) are not offered: machine translation of machine
 recognition, and YouTube answers 429 to a run of them.

 The automatic track is flagged `isAutoGenerated`, so it is listed but never
 picked on its own (`SubtitlePreference.initialTrack`).
 */

#if HYPNOS_YOUTUBE

import Foundation

struct YouTubeCaptionTrack: Sendable {
    var languageCode: String
    var name: String?
    var isAutoGenerated: Bool
    var baseURL: URL

    init?(_ json: [String: Any]) {
        guard let language = json["languageCode"] as? String,
              let base = (json["baseUrl"] as? String).flatMap(URL.init(string:)) else { return nil }
        languageCode = language
        isAutoGenerated = json["kind"] as? String == "asr"
        baseURL = base
        let names = json["name"] as? [String: Any]
        name = (names?["simpleText"] as? String) ?? ((names?["runs"] as? [[String: Any]])?.first?["text"] as? String)
    }
}

extension SubtitleSource {
    /// The video's own subtitles and its automatic captions. Nothing is
    /// requested before the YouTube approval (`YouTubeInnertube` checks it).
    static func youTube(_ id: YouTubeVideoID) -> SubtitleSource {
        let listing = YouTubeCaptionListing(id: id)
        return SubtitleSource(
            id: "youtube:\(id.rawValue)",
            tracks: { try await listing.tracks().map(\.track) },
            data: { track in try await listing.srt(for: track) }
        )
    }
}

/// One video's caption tracks, listed once so a pick fetches the URL the
/// list came with.
private actor YouTubeCaptionListing {
    let id: YouTubeVideoID
    private var listed: [(track: LibrarySubtitleTrack, url: URL)]?

    init(id: YouTubeVideoID) { self.id = id }

    func tracks() async throws -> [(track: LibrarySubtitleTrack, url: URL)] {
        if let listed { return listed }
        let all = try await YouTubeInnertube.shared.captionTracks(id)
        // People's tracks first, then the automatic one: no translations.
        let ordered = all.filter { !$0.isAutoGenerated } + all.filter(\.isAutoGenerated).prefix(1)
        let result = ordered.enumerated().map { index, caption in
            (track: LibrarySubtitleTrack(id: index, sourceId: "youtube", language: caption.languageCode,
                                         name: caption.isAutoGenerated ? nil : caption.name,
                                         isAutoGenerated: caption.isAutoGenerated),
             url: caption.baseURL)
        }
        listed = result
        return result
    }

    func srt(for track: LibrarySubtitleTrack) async throws -> Data {
        guard let entry = try await tracks().first(where: { $0.track.id == track.id }) else {
            throw URLError(.resourceUnavailable)
        }
        var components = URLComponents(url: entry.url, resolvingAgainstBaseURL: false)!
        components.queryItems = (components.queryItems ?? []).filter { $0.name != "fmt" }
            + [URLQueryItem(name: "fmt", value: "json3")]
        let (data, response) = try await URLSession.shared.data(from: components.url!)
        let status = (response as? HTTPURLResponse)?.statusCode ?? -1
        guard status == 200 else {
            throw URLError(.badServerResponse, userInfo: [NSLocalizedDescriptionKey: "Captions: HTTP \(status)"])
        }
        return Data(YouTubeCaptionConverter.subRip(fromJSON3: data).utf8)
    }
}

enum YouTubeCaptionConverter {
    /// `json3` events as SubRip. Automatic captions carry newline-only
    /// "append" events and cues that run on past the next line's start,
    /// so those are dropped and each cue ends where the next begins.
    static func subRip(fromJSON3 data: Data) -> String {
        guard let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let events = json["events"] as? [[String: Any]] else { return "" }
        var cues: [(start: Int, end: Int, text: String)] = []
        for event in events {
            guard let start = (event["tStartMs"] as? NSNumber)?.intValue,
                  let segs = event["segs"] as? [[String: Any]] else { continue }
            let text = segs.compactMap { $0["utf8"] as? String }.joined()
                .split(separator: "\n", omittingEmptySubsequences: true)
                .map { $0.trimmingCharacters(in: .whitespaces) }
                .filter { !$0.isEmpty }
                .joined(separator: "\n")
            guard !text.isEmpty else { continue }
            let duration = (event["dDurationMs"] as? NSNumber)?.intValue ?? 2000
            cues.append((start, start + max(duration, 1), text))
        }
        for index in cues.indices.dropLast() {
            cues[index].end = min(cues[index].end, max(cues[index + 1].start, cues[index].start + 1))
        }
        return cues.enumerated().map { index, cue in
            "\(index + 1)\n\(timestamp(cue.start)) --> \(timestamp(cue.end))\n\(cue.text)\n"
        }.joined(separator: "\n")
    }

    private static func timestamp(_ ms: Int) -> String {
        String(format: "%02d:%02d:%02d,%03d", ms / 3_600_000, ms / 60_000 % 60, ms / 1000 % 60, ms % 1000)
    }
}

#endif
